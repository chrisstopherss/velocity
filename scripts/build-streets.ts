import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CX, CZ, KX, KZ } from './transform.ts';

type P = [number, number];

const here = path.dirname(fileURLToPath(import.meta.url));
const dataFile = path.join(here, '..', 'apps', 'web', 'src', 'data', 'erlc-map-data.json');
const outFile = path.join(here, '..', 'apps', 'web', 'src', 'data', 'streets.data.ts');

// pixels
const SIMPLIFY = 2;
const MIN_LENGTH = 50;

const { roads } = JSON.parse(readFileSync(dataFile, 'utf8')) as { roads: { name: string; segments: P[][] }[] };

function simplify(pts: P[], tol: number): P[] {
  if (pts.length < 3) return pts;
  const keep = new Array<boolean>(pts.length).fill(false);
  keep[0] = keep[pts.length - 1] = true;
  const stack: [number, number][] = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop()!;
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const len = Math.hypot(bx - ax, by - ay) || 1e-9;
    let far = -1;
    let farDist = tol;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs((by - ay) * pts[i][0] - (bx - ax) * pts[i][1] + bx * ay - by * ax) / len;
      if (d > farDist) {
        farDist = d;
        far = i;
      }
    }
    if (far !== -1) {
      keep[far] = true;
      stack.push([a, far], [far, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const length = (pts: P[]) => pts.slice(1).reduce((sum, p, i) => sum + Math.hypot(p[0] - pts[i][0], p[1] - pts[i][1]), 0);

const rows = roads.flatMap((road) =>
  road.segments
    .map((seg) => simplify(seg.map(([x, z]): P => [KX * x + CX, KZ * z + CZ]), SIMPLIFY))
    .filter((pts) => length(pts) >= MIN_LENGTH)
    .map((pts) => ({ name: road.name, pts })),
);

const body = rows
  .map((r) => `  [${JSON.stringify(r.name)}, [${r.pts.flatMap((p) => [p[0].toFixed(1), p[1].toFixed(1)]).join(', ')}]],`)
  .join('\n');

writeFileSync(
  outFile,
  `// generated by scripts/build-streets.ts from the road lines in erlc-map-data.json, do not edit by hand
// each row is a street name and its line as x, y pairs in the 1932 px space of public/map/erlc-map.webp
export const rawStreets: [string, number[]][] = [
${body}
];
`,
);

console.log(`street lines: ${rows.length}, points: ${rows.reduce((n, r) => n + r.pts.length, 0)}`);

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CX, CZ, KX, KZ } from './transform.ts';
import { getErlcLocation } from '../apps/web/src/data/erlcLocation.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const dataFile = path.join(here, '..', 'apps', 'web', 'src', 'data', 'erlc-map-data.json');
const outFile = path.join(here, '..', 'apps', 'web', 'src', 'data', 'postals.data.ts');


const { postals } = JSON.parse(readFileSync(dataFile, 'utf8')) as {
  postals: { code: string; x: number; z: number }[];
};

const rows = postals
  .map((p) => ({
    id: Number(p.code),
    x: Math.round(KX * p.x + CX),
    y: Math.round(KZ * p.z + CZ),
    street: getErlcLocation(p.x, p.z)?.street ?? null,
  }))
  .sort((a, b) => a.id - b.id);

const body = rows.map((r) => `  [${r.id}, ${r.x}, ${r.y}, ${JSON.stringify(r.street)}],`).join('\n');

writeFileSync(
  outFile,
  `// generated by scripts/build-postals.ts from erlc-map-data.json, do not edit by hand
// positions are in the 1932 px space of public/map/erlc-map.webp
export const rawPostals: [number, number, number, string | null][] = [
${body}
];
`,
);

console.log(`postals: ${rows.length}`);
console.log(`without a street: ${rows.filter((r) => !r.street).map((r) => r.id).join(' ') || 'none'}`);

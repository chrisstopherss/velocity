import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const samplesFile = path.join(here, '.cache', 'cadly-samples.jsonl');
const seedFile = path.join(here, 'postal-seed.json');
const outFile = path.join(here, '..', 'apps', 'web', 'src', 'data', 'postals.data.ts');

// the resolver returns a few misspelled street names, these are fixed against the labels on the map image
const corrections = {
  'Independance Parkway': 'Independence Parkway',
  'Ceoar Circle': 'Cedar Circle',
  'Freicht Street': 'Freight Street',
  'Hardvest Drive': 'Harvest Drive',
  'Pock Street': 'Polk Street',
  'Aviators Lane': 'Aviator Lane',
  'Springcreek Road': 'Spring Creek Road',
};

const bounds = { x0: 700, x1: 4800, z0: 200, z1: 4600 };
const maxSeedGap = 60;

const samples = readFileSync(samplesFile, 'utf8')
  .split('\n')
  .filter(Boolean)
  .map((l) => JSON.parse(l))
  .filter((s) => s.postal && s.x >= bounds.x0 && s.x <= bounds.x1 && s.z >= bounds.z0 && s.z <= bounds.z1);

const seed = JSON.parse(readFileSync(seedFile, 'utf8'));

function mode(counts) {
  let best = null;
  for (const [key, n] of Object.entries(counts)) if (best === null || n > counts[best]) best = key;
  return best;
}

const groups = new Map();
for (const s of samples) {
  const g = groups.get(s.postal) ?? { sx: 0, sz: 0, n: 0, streets: {}, near: {} };
  g.sx += s.x;
  g.sz += s.z;
  g.n += 1;
  if (s.street) {
    const name = corrections[s.street] ?? s.street;
    g.streets[name] = (g.streets[name] ?? 0) + 1;
  }
  if (s.location) g.near[s.location] = (g.near[s.location] ?? 0) + 1;
  groups.set(s.postal, g);
}

const postals = [...groups.entries()].map(([id, g]) => ({
  id: Number(id),
  gx: g.sx / g.n,
  gz: g.sz / g.n,
  n: g.n,
  street: mode(g.streets),
  near: mode(g.near),
}));

function fitLine(pairs) {
  const n = pairs.length;
  const mx = pairs.reduce((a, p) => a + p[0], 0) / n;
  const my = pairs.reduce((a, p) => a + p[1], 0) / n;
  let num = 0;
  let den = 0;
  for (const [x, y] of pairs) {
    num += (x - mx) * (y - my);
    den += (x - mx) ** 2;
  }
  const k = num / den;
  return { k, c: my - k * mx };
}

let used = postals.filter((p) => seed[p.id]);
let fx = fitLine(used.map((p) => [p.gx, seed[p.id].x]));
let fz = fitLine(used.map((p) => [p.gz, seed[p.id].y]));
for (let round = 0; round < 4; round++) {
  const gap = (p) => Math.hypot(fx.k * p.gx + fx.c - seed[p.id].x, fz.k * p.gz + fz.c - seed[p.id].y);
  used = used.filter((p) => gap(p) <= 70);
  fx = fitLine(used.map((p) => [p.gx, seed[p.id].x]));
  fz = fitLine(used.map((p) => [p.gz, seed[p.id].y]));
}
const toPx = (p) => ({ x: Math.round(fx.k * p.gx + fx.c), y: Math.round(fz.k * p.gz + fz.c) });
const rms = Math.sqrt(
  used.reduce((a, p) => a + (toPx(p).x - seed[p.id].x) ** 2 + (toPx(p).y - seed[p.id].y) ** 2, 0) / used.length,
);

let fromSeed = 0;
let changedStreets = 0;
const rows = postals
  .sort((a, b) => a.id - b.id)
  .map((p) => {
    const t = toPx(p);
    const s = seed[p.id];
    let pos = t;
    if (s && Math.hypot(t.x - s.x, t.y - s.y) > maxSeedGap) {
      pos = { x: s.x, y: s.y };
      fromSeed += 1;
    }
    if (s && s.street && p.street && s.street !== p.street) changedStreets += 1;
    return { id: p.id, x: pos.x, y: pos.y, street: p.street, near: p.near };
  });

const missing = Object.keys(seed).filter((id) => !groups.has(id));
const newOnes = rows.filter((r) => !seed[r.id]).map((r) => r.id);

const body = rows
  .map((r) => `  [${r.id}, ${r.x}, ${r.y}, ${JSON.stringify(r.street)}, ${JSON.stringify(r.near)}],`)
  .join('\n');

writeFileSync(
  outFile,
  `// generated by scripts/build-postals.mjs from CADLY resolver samples, do not edit by hand
// positions are in the 1932 px space of public/map/erlc-map.webp
export const rawPostals: [number, number, number, string | null, string | null][] = [
${body}
];
`,
);

console.log(`postals with samples: ${rows.length}`);
console.log(`transform: px = ${fx.k.toFixed(4)} * x + ${fx.c.toFixed(1)}, py = ${fz.k.toFixed(4)} * z + ${fz.c.toFixed(1)}`);
console.log(`fit used ${used.length} postals, rms error ${rms.toFixed(1)} px`);
console.log(`kept hand-placed position for ${fromSeed} postals (gap over ${maxSeedGap}px)`);
console.log(`street name changed for ${changedStreets} postals`);
console.log(`postals with no street: ${rows.filter((r) => !r.street).map((r) => r.id).join(' ') || 'none'}`);
console.log(`in seed but not found by the API: ${missing.join(' ') || 'none'}`);
console.log(`new postals not in seed: ${newOnes.length}`);
